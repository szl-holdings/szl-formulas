"""Shipped-copy fixtures: run the kernel tests against what the Hub serves.

The Hub layout is generated by scripts/szl_kernel_publish.py; nothing under build/ is
committed. ``shipped_root(copy)`` returns a directory that holds ``szl_formulas/`` for
each copy in ``COPIES``: the GitHub source (``torch-ext``) and both published variants
(``build/torch-cpu`` and ``build/torch-universal``), materialised from the working tree
with the publisher's own package map (.github/hf-kernels.json) and normalisation.
"""
from __future__ import annotations

import importlib.util
import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
COPIES = ["torch-ext", "build/torch-cpu", "build/torch-universal"]

_spec = importlib.util.spec_from_file_location("_szl_kernel_publish_conftest",
                                               ROOT / "scripts" / "szl_kernel_publish.py")
kp = importlib.util.module_from_spec(_spec)
sys.modules[_spec.name] = kp
_spec.loader.exec_module(kp)


def _materialise(out: Path) -> None:
    cfg = kp.find_kernel(ROOT, "SZLHOLDINGS/szl-formulas")
    for pkg in cfg.packages:
        src = ROOT / pkg.src
        files = sorted(p for p in src.rglob("*") if p.is_file()
                       and "__pycache__" not in p.parts and p.suffix not in (".pyc", ".pyo"))
        assert files, f"{pkg.src} is empty"
        for path in files:
            rel = path.relative_to(src).as_posix()
            data = kp.normalize_text(f"{pkg.src}/{rel}", path.read_bytes())
            for variant in kp.VARIANTS:
                target = out / "build" / variant / pkg.name / rel
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_bytes(data)


@pytest.fixture(scope="session")
def shipped_root(tmp_path_factory):
    out = tmp_path_factory.mktemp("shipped")
    _materialise(out)

    def root(copy: str) -> Path:
        if copy == "torch-ext":
            return ROOT / "torch-ext"
        assert copy in COPIES, copy
        return out / copy

    return root
